<?php
/**
 * File-based storage shared by the pre-WordPress firewall and the plugin:
 * config, IP blocks, rate counters and the attack log queue.
 *
 * Standalone: must not depend on WordPress.
 *
 * @package Bastion_Security
 */

if ( class_exists( 'Bastion_Waf_Storage', false ) ) {
	return;
}

class Bastion_Waf_Storage {

	const LOG_HEADER   = "<?php exit; ?>\n";
	const LOG_MAX_SIZE = 5242880; // 5 MB; protects disk if the importer is not running.
	const MAX_BLOCKS   = 10000;

	/** @var string */
	public $dir;

	/** @var array|null */
	private $blocks;

	public function __construct( $dir ) {
		$this->dir = rtrim( $dir, '/\\' );
	}

	/* ------------------------------------------------------------------ files */

	public function path( $name ) {
		return $this->dir . '/' . $name;
	}

	public function ensure_dir( $sub = '' ) {
		$dir = $sub ? $this->path( $sub ) : $this->dir;
		if ( ! is_dir( $dir ) ) {
			@mkdir( $dir, 0755, true );
		}
		// Deny web access on Apache/LiteSpeed/IIS; files that matter are .php with an exit guard anyway.
		if ( ! file_exists( $dir . '/.htaccess' ) ) {
			@file_put_contents( $dir . '/.htaccess', "# Bastion Security\n<IfModule mod_authz_core.c>\nRequire all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\nOrder allow,deny\nDeny from all\n</IfModule>\n" );
		}
		if ( ! file_exists( $dir . '/index.php' ) ) {
			@file_put_contents( $dir . '/index.php', "<?php // Silence is golden.\n" );
		}
		if ( ! file_exists( $dir . '/web.config' ) ) {
			@file_put_contents( $dir . '/web.config', '<?xml version="1.0"?><configuration><system.webServer><authorization><deny users="*" /></authorization></system.webServer></configuration>' );
		}
		return is_dir( $dir ) && is_writable( $dir );
	}

	public function read_php_array( $name ) {
		$file = $this->path( $name );
		if ( ! is_file( $file ) ) {
			return array();
		}
		$data = @include $file;
		return is_array( $data ) ? $data : array();
	}

	/** Atomic write of a PHP file returning an array (fast: served from opcache). */
	public function write_php_array( $name, array $data ) {
		$this->ensure_dir();
		$file = $this->path( $name );
		$tmp  = $file . '.' . getmypid() . '.' . mt_rand() . '.tmp';
		$php  = "<?php\n// Generated by Bastion Security. Do not edit.\nreturn " . var_export( $data, true ) . ";\n";
		if ( false === @file_put_contents( $tmp, $php, LOCK_EX ) ) {
			return false;
		}
		if ( ! @rename( $tmp, $file ) ) {
			@unlink( $tmp );
			return false;
		}
		if ( function_exists( 'opcache_invalidate' ) ) {
			@opcache_invalidate( $file, true );
		}
		return true;
	}

	public function load_config() {
		return $this->read_php_array( 'config.php' );
	}

	/* ----------------------------------------------------------------- blocks */

	public function get_blocks() {
		if ( null === $this->blocks ) {
			$this->blocks = $this->read_php_array( 'blocks.php' );
		}
		return $this->blocks;
	}

	/**
	 * @return array|null Block entry [until, reason, scope, created] or null.
	 */
	public function get_block( $ip ) {
		$blocks = $this->get_blocks();
		if ( ! isset( $blocks[ $ip ] ) ) {
			return null;
		}
		$b = $blocks[ $ip ];
		if ( ! empty( $b['until'] ) && $b['until'] < time() ) {
			return null;
		}
		return $b;
	}

	/**
	 * @param string $ip      IP.
	 * @param int    $seconds 0 = permanent.
	 * @param string $reason  Human reason.
	 * @param string $scope   all | login.
	 */
	public function add_block( $ip, $seconds, $reason, $scope = 'all' ) {
		return $this->mutate_blocks(
			function ( $blocks ) use ( $ip, $seconds, $reason, $scope ) {
				$existing = isset( $blocks[ $ip ] ) ? $blocks[ $ip ] : null;
				// Never downgrade a permanent or site-wide block.
				if ( $existing && ( empty( $existing['until'] ) || $existing['until'] > time() ) ) {
					if ( empty( $existing['until'] ) ) {
						return $blocks;
					}
					if ( 'all' === $existing['scope'] && 'login' === $scope ) {
						return $blocks;
					}
				}
				$blocks[ $ip ] = array(
					'until'   => $seconds > 0 ? time() + (int) $seconds : 0,
					'reason'  => substr( (string) $reason, 0, 200 ),
					'scope'   => 'login' === $scope ? 'login' : 'all',
					'created' => time(),
				);
				return $blocks;
			}
		);
	}

	public function remove_block( $ip ) {
		return $this->mutate_blocks(
			function ( $blocks ) use ( $ip ) {
				unset( $blocks[ $ip ] );
				return $blocks;
			}
		);
	}

	private function mutate_blocks( $callback ) {
		$this->ensure_dir();
		$lock = @fopen( $this->path( 'blocks.lock' ), 'c' );
		if ( $lock ) {
			flock( $lock, LOCK_EX );
		}
		$this->blocks = null;
		$blocks       = $this->get_blocks();
		$blocks       = $callback( $blocks );
		// Prune expired entries and cap size (drop the oldest temporary blocks first).
		$now = time();
		foreach ( $blocks as $k => $b ) {
			if ( ! empty( $b['until'] ) && $b['until'] < $now ) {
				unset( $blocks[ $k ] );
			}
		}
		if ( count( $blocks ) > self::MAX_BLOCKS ) {
			uasort(
				$blocks,
				function ( $a, $b ) {
					return $a['created'] - $b['created'];
				}
			);
			$blocks = array_slice( $blocks, -self::MAX_BLOCKS, null, true );
		}
		$ok           = $this->write_php_array( 'blocks.php', $blocks );
		$this->blocks = $blocks;
		if ( $lock ) {
			flock( $lock, LOCK_UN );
			fclose( $lock );
		}
		return $ok;
	}

	/* ------------------------------------------------------------ rate limits */

	/**
	 * Fixed-window counter. Uses APCu when available, otherwise small lock-protected files.
	 *
	 * @return int Count in the current window after adding $amount.
	 */
	public function hit( $key, $window, $amount = 1 ) {
		$window = max( 1, (int) $window );
		$bucket = (int) floor( time() / $window );
		$k      = 'bastion:' . $key . ':' . $bucket;

		if ( function_exists( 'apcu_enabled' ) && apcu_enabled() ) {
			apcu_add( $k, 0, $window + 5 );
			$v = apcu_inc( $k, $amount );
			return false === $v ? $amount : (int) $v;
		}

		$this->ensure_dir( 'rate' );
		$file = $this->path( 'rate/' . md5( $key ) );
		$fh   = @fopen( $file, 'c+' );
		if ( ! $fh ) {
			return $amount;
		}
		flock( $fh, LOCK_EX );
		$raw   = stream_get_contents( $fh );
		$count = 0;
		if ( $raw && preg_match( '/^(\d+)\|(\d+)$/', $raw, $m ) && (int) $m[1] === $bucket ) {
			$count = (int) $m[2];
		}
		$count += $amount;
		ftruncate( $fh, 0 );
		rewind( $fh );
		fwrite( $fh, $bucket . '|' . $count );
		fflush( $fh );
		flock( $fh, LOCK_UN );
		fclose( $fh );
		return $count;
	}

	public function reset_counter( $key, $window ) {
		$bucket = (int) floor( time() / max( 1, (int) $window ) );
		if ( function_exists( 'apcu_enabled' ) && apcu_enabled() ) {
			apcu_delete( 'bastion:' . $key . ':' . $bucket );
			return;
		}
		@unlink( $this->path( 'rate/' . md5( $key ) ) );
	}

	public function cleanup_rate_files( $max_age = 7200 ) {
		$dir = $this->path( 'rate' );
		if ( ! is_dir( $dir ) ) {
			return;
		}
		foreach ( (array) glob( $dir . '/*' ) as $f ) {
			if ( is_file( $f ) && strlen( basename( $f ) ) === 32 && filemtime( $f ) < time() - $max_age ) {
				@unlink( $f );
			}
		}
	}

	/* -------------------------------------------------------------------- log */

	public function log( array $entry ) {
		$file = $this->path( 'log.php' );
		if ( is_file( $file ) && @filesize( $file ) > self::LOG_MAX_SIZE ) {
			return;
		}
		$this->ensure_dir();
		$line = json_encode( $entry, JSON_UNESCAPED_SLASHES | JSON_PARTIAL_OUTPUT_ON_ERROR ) . "\n";
		if ( ! is_file( $file ) ) {
			@file_put_contents( $file, self::LOG_HEADER, LOCK_EX );
		}
		@file_put_contents( $file, $line, FILE_APPEND | LOCK_EX );
	}

	/** Atomically take all queued log entries. */
	public function drain_log() {
		$file = $this->path( 'log.php' );
		if ( ! is_file( $file ) ) {
			return array();
		}
		$fh = @fopen( $file, 'c+' );
		if ( ! $fh ) {
			return array();
		}
		flock( $fh, LOCK_EX );
		$raw = stream_get_contents( $fh );
		ftruncate( $fh, 0 );
		rewind( $fh );
		fwrite( $fh, self::LOG_HEADER );
		fflush( $fh );
		flock( $fh, LOCK_UN );
		fclose( $fh );

		$out = array();
		foreach ( explode( "\n", (string) $raw ) as $line ) {
			if ( '' === $line || '<' === $line[0] ) {
				continue;
			}
			$row = json_decode( $line, true );
			if ( is_array( $row ) ) {
				$out[] = $row;
			}
		}
		return $out;
	}
}
